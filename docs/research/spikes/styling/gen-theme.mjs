// One source, two outputs: reads ripple/tokens.css (plain CSS, the source of truth) and writes
// ripple/theme.css, a Tailwind v4 `@theme reference` block that only teaches Tailwind the names.
import { readFileSync, writeFileSync } from 'node:fs'
const src = readFileSync(new URL('./ripple/tokens.css', import.meta.url), 'utf8')
const NAMESPACES = /^--(color|radius|spacing|container|font|text|shadow|ease|z-index|transition-duration)(-|$)/
// first derived block = the static declarations (":root,\n  [data-scheme] {" ... "}")
const block = src.slice(src.indexOf('[data-scheme] {', src.indexOf('3. DERIVED')))
const body = block.slice(block.indexOf('{') + 1, block.indexOf('\n  }'))
const decls = [...body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].filter(([, n]) => NAMESPACES.test(n))
const out = `/* GENERATED by gen-theme.mjs from tokens.css. Do not edit.
   \`reference\`: Tailwind emits no variables; utilities compile to var(--name, <this value>). */
@theme reference {
${decls.map(([, n, v]) => `  ${n}: ${v.replace(/\s+/g, ' ').trim()};`).join('\n')}
  --z-index-raised: var(--rp-z-raised);
  --z-index-sticky: var(--rp-z-sticky);
  --z-index-overlay: var(--rp-z-overlay);
  --z-index-toast: var(--rp-z-toast);
  --transition-duration-fast: var(--rp-duration-fast);
  --transition-duration-base: var(--rp-duration-base);
  --transition-duration-slow: var(--rp-duration-slow);
}
`
writeFileSync(new URL('./ripple/theme.css', import.meta.url), out)
console.log(`theme.css: ${decls.length + 7} tokens`)
