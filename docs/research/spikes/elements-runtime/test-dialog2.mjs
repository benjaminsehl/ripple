import { createRequire } from "node:module"
import { serve } from "./server.mjs"
const { chromium } = createRequire(import.meta.url)("playwright")
const { server, url } = await serve()
const browser = await chromium.launch()
const page = await browser.newPage()
page.on("pageerror", (e) => console.log("PAGEERROR", e.message))
const check = (name, pass, info = "") => console.log(`${pass ? "PASS" : "FAIL"}  ${name}${info ? "  " + info : ""}`)
await page.goto(url + "/site/dialog2.html")
await page.waitForFunction(() => customElements.get("rp-dialog"))
await page.waitForTimeout(100)
let d = await page.evaluate(() => window.__d.splice(0))
check("data-default-open: dialog opens on connect, openchange reason imperative", await page.evaluate(() => document.getElementById("welcome").open) && JSON.stringify(d) === JSON.stringify([{ id: "welcome", value: true, reason: "imperative" }]), JSON.stringify(d))
await page.click("#welcome button"); await page.waitForTimeout(50)
await page.evaluate(async () => { const el = document.getElementById("welcome").parentElement; const p = el.parentNode, n = el.nextSibling; el.remove(); await new Promise((r) => setTimeout(r, 50)); p.insertBefore(el, n); await new Promise((r) => setTimeout(r, 50)) })
check("data-default-open: a reconnect does not reopen the dialog", await page.evaluate(() => !document.getElementById("welcome").open))
await page.evaluate(() => window.__d.splice(0))
await page.click("#open-nav"); await page.waitForTimeout(50)
await page.click("#sum"); await page.waitForTimeout(50)
d = await page.evaluate(() => window.__d.splice(0))
check("nested <details> toggling inside the dialog fires no openchange", d.length === 1 && d[0].id === "menu" && await page.evaluate(() => document.getElementById("sub").open), JSON.stringify(d))
await page.evaluate(() => window.navigation.addEventListener("navigate", (e) => { if (e.canIntercept) e.intercept({ handler() { return Promise.resolve() } }) }))
await page.click("#inner-link"); await page.waitForTimeout(100)
d = await page.evaluate(() => window.__d.splice(0))
check("intercepted link navigation closes the dialog, reason link-press", JSON.stringify(d) === JSON.stringify([{ id: "menu", value: false, reason: "link-press" }]), JSON.stringify(d) + " url=" + page.url().split("/").pop())
await page.click("#open-nav"); await page.waitForTimeout(50)
await page.evaluate(() => window.__d.splice(0))
await page.evaluate(() => history.pushState({}, "", "?filter=1")); await page.waitForTimeout(100)
check("history.pushState does not close the dialog", await page.evaluate(() => document.getElementById("menu").open))
await browser.close(); server.close()
